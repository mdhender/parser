package lemon

import (
	"bytes"
	"fmt"
	"strings"
)

func ruleText(r *Rule) string {
	var b strings.Builder
	reportRulePrint(&b, r, -1)
	return b.String()
}

func textOr(s *string, fallback string) string {
	if s != nil {
		return *s
	}
	return fallback
}

func (g *Grammar) reportTable(argv0 string, o options) {
	// Set ranges even if opening the template fails, as ReportTable does.
	g.MinShiftReduce = len(g.States)
	g.ErrAction = g.MinShiftReduce + len(g.Rules)
	g.AccAction, g.NoAction, g.MinReduce = g.ErrAction+1, g.ErrAction+2, g.ErrAction+3
	g.MaxAction = g.MinReduce + len(g.Rules)
	template := g.openTemplate(argv0, o)
	if template == nil {
		return
	}
	out := g.openOutput(".c", o)
	if out == nil {
		return
	}
	defer out.Close()
	if o.flags['S'] {
		before := g.errors
		g.reportSQL(o)
		if g.errors != before {
			return
		}
	}
	e := &cOutput{w: out, line: 1, template: template, name: g.Name}
	e.print("/* This file is automatically generated by Lemon from input grammar\n** source file \"%s\"", g.Filename)
	used := false
	for _, b := range g.defineUsed {
		used = used || b
	}
	if !used {
		e.print(".\n*/\n")
	} else {
		e.print(" with these options:\n**\n")
		for i, d := range g.defines {
			if g.defineUsed[i] {
				e.print("**   -D%s\n", d)
			}
		}
		e.print("*/\n")
	}
	include := textOr(g.Include, "")
	for i := 0; i < len(include) && space(include[i]); i++ {
		if include[i] == '\n' {
			include = include[i+1:]
			i = -1
		}
	}
	e.transfer(strings.HasPrefix(include, "/"))
	g.templatePrint(e, &include)
	if o.flags['m'] {
		e.print("#include \"%s\"\n", g.fileName(".h", o))
	}
	e.transfer(false)
	prefix := textOr(g.TokenPrefix, "")
	if o.flags['m'] {
		e.print("#if INTERFACE\n")
	} else {
		e.print("#ifndef %s%s\n", prefix, g.Symbols[1].Name)
		e.line-- // Upstream does not count this line.
	}
	for i := 1; i < g.NTerminal; i++ {
		e.print("#define %s%-30s %2d\n", prefix, g.Symbols[i].Name, i)
	}
	e.print("#endif\n")
	e.transfer(false)
	codeType, codeSize := minimumSizeType(0, g.NSymbol)
	actionType, actionSize := minimumSizeType(0, g.MaxAction)
	e.print("#define YYCODETYPE %s\n#define YYNOCODE %d\n#define YYACTIONTYPE %s\n", codeType, g.NSymbol, actionType)
	if g.Wildcard != nil {
		e.print("#define YYWILDCARD %d\n", g.Wildcard.Index)
	}
	var union bytes.Buffer
	g.stackUnion(&union, o.flags['m'])
	e.print("%s", union.String())
	e.print("#ifndef YYSTACKDEPTH\n#define YYSTACKDEPTH %s\n#endif\n", textOr(g.StackSize, "100"))
	if o.flags['m'] {
		e.print("#if INTERFACE\n")
	}
	name := textOr(g.Name, "Parse")
	emitArg := func(kind string, arg *string) {
		z := textOr(arg, "")
		if z == "" {
			for _, suffix := range []string{"SDECL", "PDECL", "PARAM", "FETCH", "STORE"} {
				e.print("#define %s%s_%s\n", name, kind, suffix)
			}
			return
		}
		i := len(z)
		for i >= 1 && space(z[i-1]) {
			i--
		}
		for i >= 1 && (alnum(z[i-1]) || z[i-1] == '_') {
			i--
		}
		v := z[i:]
		e.print("#define %s%s_SDECL %s;\n#define %s%s_PDECL ,%s\n#define %s%s_PARAM ,%s\n", name, kind, z, name, kind, z, name, kind, v)
		e.print("#define %s%s_FETCH %s=yypParser->%s;\n#define %s%s_STORE yypParser->%s=%s;\n", name, kind, z, v, name, kind, v, v)
	}
	emitArg("ARG", g.ExtraArgument)
	e.print("#define YYREALLOC %s\n#define YYFREE %s\n", textOr(g.Realloc, "realloc"), textOr(g.Free, "free"))
	e.print("#define YYDYNSTACK %d\n", boolInt(g.Realloc != nil && g.Free != nil))
	emitArg("CTX", g.ExtraContext)
	if o.flags['m'] {
		e.print("#endif\n")
	}
	if g.ErrorSymbol != nil && g.ErrorSymbol.UseCount != 0 {
		e.print("#define YYERRORSYMBOL %d\n#define YYERRSYMDT yy%d\n", g.ErrorSymbol.Index, g.ErrorSymbol.Dtnum)
	}
	if g.HasFallback {
		e.print("#define YYFALLBACK 1\n")
	}
	t := g.BuildTables()
	for _, d := range []struct {
		name string
		n    int
	}{
		{"YYNSTATE            ", g.NXState}, {"YYNRULE             ", len(g.Rules)}, {"YYNRULE_WITH_ACTION ", g.NRuleWithAction}, {"YYNTOKEN            ", g.NTerminal},
		{"YY_MAX_SHIFT        ", g.NXState - 1}, {"YY_MIN_SHIFTREDUCE  ", g.MinShiftReduce}, {"YY_MAX_SHIFTREDUCE  ", g.MinShiftReduce + len(g.Rules) - 1},
		{"YY_ERROR_ACTION     ", g.ErrAction}, {"YY_ACCEPT_ACTION    ", g.AccAction}, {"YY_NO_ACTION        ", g.NoAction}, {"YY_MIN_REDUCE       ", g.MinReduce}, {"YY_MAX_REDUCE       ", g.MinReduce + len(g.Rules) - 1},
	} {
		e.print("#define %s %d\n", d.name, d.n)
	}
	mn, mx := 0, 0
	for _, s := range g.Symbols[:g.NSymbol] {
		if s.Type != Terminal && s.Destructor != nil {
			if mn == 0 || s.Index < mn {
				mn = s.Index
			}
			mx = max(mx, s.Index)
		}
	}
	if g.TokenDestructor != nil {
		mn = 0
	}
	if g.DefaultDestructor != nil {
		mx = g.NSymbol - 1
	}
	e.print("#define YY_MIN_DSTRCTR       %d\n#define YY_MAX_DSTRCTR       %d\n", mn, mx)
	e.transfer(false)
	g.nActionTab, g.nLookaheadTab = len(t.Action), t.packed.nAction
	g.tableSize = len(t.Action)*actionSize + t.packed.nAction*codeSize
	emitArray := func(typ, name string, values []int) {
		e.print("static const %s %s[] = {\n", typ, name)
		for i, v := range values {
			if i%10 == 0 {
				e.print(" /* %5d */ ", i)
			}
			e.print(" %4d,", v)
			if i%10 == 9 || i == len(values)-1 {
				e.print("\n")
			}
		}
		e.print("};\n")
	}
	e.print("#define YY_ACTTAB_COUNT (%d)\n", len(t.Action))
	emitArray("YYACTIONTYPE", "yy_action", t.Action)
	emitArray("YYCODETYPE", "yy_lookahead", t.Lookahead)
	e.print("#define YY_SHIFT_COUNT    (%d)\n#define YY_SHIFT_MIN      (%d)\n#define YY_SHIFT_MAX      (%d)\n", len(t.Shift)-1, t.MinTknOfst, t.MaxTknOfst)
	typ, size := minimumSizeType(t.MinTknOfst, g.NTerminal+len(t.Action))
	g.tableSize += len(t.Shift) * size
	emitArray(typ, "yy_shift_ofst", t.Shift)
	e.print("#define YY_REDUCE_COUNT (%d)\n#define YY_REDUCE_MIN   (%d)\n#define YY_REDUCE_MAX   (%d)\n", len(t.Reduce)-1, t.MinNtOfst, t.MaxNtOfst)
	typ, size = minimumSizeType(t.MinNtOfst-1, t.MaxNtOfst)
	g.tableSize += len(t.Reduce) * size
	emitArray(typ, "yy_reduce_ofst", t.Reduce)
	g.tableSize += len(t.Default) * actionSize
	emitArray("YYACTIONTYPE", "yy_default", t.Default)
	e.transfer(false)
	if g.HasFallback {
		g.tableSize += g.NTerminal * codeSize
		for _, s := range g.Symbols[:g.NTerminal] {
			if s.Fallback == nil {
				e.print("    0,  /* %10s => nothing */\n", s.Name)
			} else {
				e.print("  %3d,  /* %10s => %s */\n", s.Fallback.Index, s.Name, s.Fallback.Name)
			}
		}
	}
	e.transfer(false)
	for i, s := range g.Symbols[:g.NSymbol] {
		e.print("  /* %4d */ \"%s\",\n", i, s.Name)
	}
	e.transfer(false)
	for i, r := range g.Rules {
		e.print(" /* %3d */ \"%s\",\n", i, ruleText(r))
	}
	e.transfer(false)
	g.emitDestructors(e)
	e.transfer(false)
	g.templatePrint(e, g.StackOverflow)
	e.transfer(false)
	for i, r := range g.Rules {
		e.print("  %4d,  /* (%d) %s */\n", r.LHS.Index, i, ruleText(r))
	}
	e.transfer(false)
	for i, r := range g.Rules {
		e.print("  %3d,  /* (%d) %s */\n", -len(r.RHS), i, ruleText(r))
	}
	e.transfer(false)
	needLHS := false
	for _, r := range g.Rules {
		if g.translateCode(r) {
			needLHS = true
		}
	}
	if needLHS {
		e.print("        YYMINORTYPE yylhsminor;\n")
	}
	emitted := make([]bool, len(g.Rules))
	for i, r := range g.Rules {
		if emitted[i] || r.NoCode {
			continue
		}
		e.print("      case %d: /* %s */\n", r.IRule, ruleText(r))
		for j := i + 1; j < len(g.Rules); j++ {
			s := g.Rules[j]
			if equalText(r.Code, s.Code) && equalText(r.CodePrefix, s.CodePrefix) && equalText(r.CodeSuffix, s.CodeSuffix) {
				e.print("      case %d: /* %s */ yytestcase(yyruleno==%d);\n", s.IRule, ruleText(s), s.IRule)
				emitted[j] = true
			}
		}
		g.emitCode(e, r)
		e.print("        break;\n")
		emitted[i] = true
	}
	e.print("      default:\n")
	for i, r := range g.Rules {
		if emitted[i] {
			continue
		}
		e.print("      /* (%d) %s", r.IRule, ruleText(r))
		if r.NeverReduce {
			e.print(" (NEVER REDUCES) */ assert(yyruleno!=%d);\n", r.IRule)
		} else if r.DoesReduce {
			e.print(" */ yytestcase(yyruleno==%d);\n", r.IRule)
		} else {
			e.print(" (OPTIMIZED OUT) */ assert(yyruleno!=%d);\n", r.IRule)
		}
	}
	e.print("        break;\n")
	e.transfer(false)
	for _, hook := range []*string{g.ParseFailure, g.SyntaxError, g.ParseAccept} {
		g.templatePrint(e, hook)
		e.transfer(false)
	}
	g.templatePrint(e, g.ExtraCode)
}

func equalText(a, b *string) bool {
	if a == nil || b == nil {
		return a == b
	}
	return *a == *b
}

func (g *Grammar) emitCode(e *cOutput, r *Rule) {
	if r.CodePrefix != nil && *r.CodePrefix != "" {
		e.print("{%s", *r.CodePrefix)
	}
	if r.Code != nil {
		if !g.noLineNumbers {
			e.lineDir(r.Line, g.Filename)
		}
		e.print("{%s}\n", *r.Code)
		if !g.noLineNumbers {
			e.lineDir(e.line+1, g.outname)
		}
	}
	if r.CodeSuffix != nil && *r.CodeSuffix != "" {
		e.print("%s", *r.CodeSuffix)
	}
	if r.CodePrefix != nil {
		e.print("}\n")
	}
}

func (g *Grammar) emitDestructor(e *cOutput, s *Symbol) {
	code := g.DefaultDestructor
	if s.Type == Terminal {
		code = g.TokenDestructor
	} else if s.Destructor != nil {
		code = s.Destructor
	}
	if code == nil {
		return
	}
	e.print("{\n")
	if s.Type != Terminal && s.Destructor != nil && !g.noLineNumbers {
		e.lineDir(s.DestLine, g.Filename)
	}
	e.print("%s\n", strings.ReplaceAll(*code, "$$", fmt.Sprintf("(yypminor->yy%d)", s.Dtnum)))
	if !g.noLineNumbers {
		e.lineDir(e.line+1, g.outname)
	}
	e.print("}\n")
}

func (g *Grammar) emitDestructors(e *cOutput) {
	if g.TokenDestructor != nil {
		var first *Symbol
		for _, s := range g.Symbols[:g.NSymbol] {
			if s.Type != Terminal {
				continue
			}
			if first == nil {
				e.print("      /* TERMINAL Destructor */\n")
				first = s
			}
			e.print("    case %d: /* %s */\n", s.Index, s.Name)
		}
		if first != nil {
			g.emitDestructor(e, first)
			e.print("      break;\n")
		}
	}
	if g.DefaultDestructor != nil {
		var last *Symbol
		for _, s := range g.Symbols[:g.NSymbol] {
			if s.Type == Terminal || s.Index <= 0 || s.Destructor != nil {
				continue
			}
			if last == nil {
				e.print("      /* Default NON-TERMINAL Destructor */\n")
			}
			e.print("    case %d: /* %s */\n", s.Index, s.Name)
			last = s
		}
		if last != nil {
			g.emitDestructor(e, last)
		}
		e.print("      break;\n")
	}
	for i, s := range g.Symbols[:g.NSymbol] {
		if s.Type == Terminal || s.Destructor == nil || s.DestLine < 0 {
			continue
		}
		e.print("    case %d: /* %s */\n", s.Index, s.Name)
		for _, other := range g.Symbols[i+1 : g.NSymbol] {
			if other.Type != Terminal && other.Destructor != nil && other.Dtnum == s.Dtnum && *other.Destructor == *s.Destructor {
				e.print("    case %d: /* %s */\n", other.Index, other.Name)
				other.DestLine = -1
			}
		}
		g.emitDestructor(e, s)
		e.print("      break;\n")
	}
}
